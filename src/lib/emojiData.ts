/** 最近使用的表情存储 key */
export const RECENT_EMOJI_KEY = "jot-recent-emojis";

/** 最近使用最多保留数量 */
export const MAX_RECENT = 20;

/**
 * 从 localStorage 读取最近使用的表情列表
 */
export function getRecentEmojis(): string[] {
  try {
    const raw = localStorage.getItem(RECENT_EMOJI_KEY);
    if (!raw) return [];
    return JSON.parse(raw) as string[];
  } catch {
    return [];
  }
}

/**
 * 记录一个表情到最近使用列表
 */
export function addRecentEmoji(emoji: string): void {
  try {
    const list = getRecentEmojis().filter((e) => e !== emoji);
    list.unshift(emoji);
    localStorage.setItem(
      RECENT_EMOJI_KEY,
      JSON.stringify(list.slice(0, MAX_RECENT)),
    );
  } catch {
    // localStorage 不可用时静默忽略
  }
}
